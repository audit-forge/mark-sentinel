"""Generate per-customer, double-clickable installer packages.

The admin app calls these functions at request time with the customer's
server URL and agent token baked in. The resulting file is served as a
download — the end user just double-clicks it.

  Windows:  a NSIS-compiled .exe that elevates via UAC and runs install.ps1
  macOS:    a .app bundle that prompts for admin privileges via osascript
            and runs install.sh

Both download the actual Nuitka-compiled agent binary from the server during
installation, so the installer package itself stays small.
"""

import os
import shutil
import subprocess
import tempfile
import zipfile

from arckon_version import INSTALLER_VERSION

_NSI_TEMPLATE = """\
; Auto-generated by the Arckon admin — do not edit.
!include "LogicLib.nsh"

!define SERVER "__SERVER__"
!define TOKEN "__TOKEN__"
!define CUSTOMER_NAME "__CUSTOMER_NAME__"
!define INSTALLER_VERSION "__INSTALLER_VERSION__"

Name "Arckon Agent Installer v${INSTALLER_VERSION} — __CUSTOMER_NAME__"
OutFile "__OUTPUT__"
Unicode true
RequestExecutionLevel admin
ShowInstDetails show
SetCompressor /SOLID lzma
InstallDir "$PROGRAMFILES64\\Arckon"
VIProductVersion "${INSTALLER_VERSION}"
VIAddVersionKey /LANG=1033 "ProductName" "Arckon Agent Installer"
VIAddVersionKey /LANG=1033 "ProductVersion" "${INSTALLER_VERSION}"
VIAddVersionKey /LANG=1033 "FileVersion" "${INSTALLER_VERSION}"

Page instfiles
UninstPage instfiles

Section "Install Arckon Agent"
  SetRegView 64
  SetOutPath "$TEMP\\arckon-install"
  File "install.ps1"

  DetailPrint "Installing Arckon Agent for __CUSTOMER_NAME__"
  DetailPrint "Installer version: ${INSTALLER_VERSION}"
  DetailPrint "Server: __SERVER__"
  DetailPrint ""

  nsExec::ExecToLog 'powershell.exe -ExecutionPolicy Bypass -NoProfile -NonInteractive -File "$TEMP\\arckon-install\\install.ps1" -Server "__SERVER__" -Token "__TOKEN__" -NoPrompt'
  Pop $0

  DetailPrint ""
  DetailPrint "Installer exited with code: $0"

  Delete "$TEMP\\arckon-install\\install.ps1"
  RMDir "$TEMP\\arckon-install"

  ${If} $0 == 0
    SetOutPath "$INSTDIR"
    File "uninstall.ps1"
    WriteUninstaller "$INSTDIR\\Uninstall Arckon Agent.exe"
    WriteRegStr HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent" "DisplayName" "Arckon Agent"
    WriteRegStr HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent" "DisplayVersion" "${INSTALLER_VERSION}"
    WriteRegStr HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent" "Publisher" "RiskRaven"
    WriteRegStr HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent" "UninstallString" "$\\\"$INSTDIR\\Uninstall Arckon Agent.exe$\\\""
    MessageBox MB_OK "Arckon Agent installed successfully.$\\r$\\n$\\r$\\nInstaller version: ${INSTALLER_VERSION}$\\r$\\nThe service is running in the background."
  ${Else}
    MessageBox MB_OK|MB_ICONSTOP "Installation failed (exit code $0).$\\r$\\n$\\r$\\nPlease contact your IT administrator or RiskRaven support."
    SetErrorLevel $0
  ${EndIf}
SectionEnd

Section "Uninstall"
  SetRegView 64
  DeleteRegKey HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent"
  SetRegView 32
  DeleteRegKey HKLM "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ArckonAgent"
  SetRegView 64
  SetOutPath "$TEMP\\arckon-uninstall"
  File "uninstall.ps1"
  nsExec::ExecToLog 'powershell.exe -ExecutionPolicy Bypass -NoProfile -NonInteractive -File "$TEMP\\arckon-uninstall\\uninstall.ps1" -Force'
  Pop $0
  Delete "$TEMP\\arckon-uninstall\\uninstall.ps1"
  RMDir "$TEMP\\arckon-uninstall"
  RMDir /r "$INSTDIR"
SectionEnd
"""

_APP_LAUNCHER = """\
#!/bin/bash
# Arckon Agent installer — per-customer, baked-in credentials.
# Double-clicking this .app runs install.sh with admin privileges.
set -euo pipefail

RESOURCES="$(dirname "$(dirname "$0")")/Resources"
SERVER="$(cat "$RESOURCES/server.txt")"
TOKEN="$(cat "$RESOURCES/token.txt")"
INSTALL_SH="$RESOURCES/install.sh"

OUTPUT=$(osascript -e \
  "do shell script \\"bash '$INSTALL_SH' --server '$SERVER' --token '$TOKEN' 2>&1\\" \
   with administrator privileges \
   with prompt \\"Arckon Agent needs to install system components.\\"" 2>&1) || true

if echo "$OUTPUT" | grep -qi "installed successfully"; then
  osascript -e 'display dialog "Arckon Agent installed successfully." buttons {"OK"} default button 1 with title "Arckon Installer" with icon note' 2>/dev/null || true
else
  osascript -e "display dialog \\"Installation did not complete.\\n\\n$OUTPUT\\" buttons {\\"OK\\"} default button 1 with title \\"Arckon Installer\\" with icon stop" 2>/dev/null || true
fi
"""

_INFO_PLIST = """\
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>              <string>Arckon Installer</string>
  <key>CFBundleDisplayName</key>       <string>Arckon Installer</string>
  <key>CFBundleIdentifier</key>        <string>ai.mfdynamics.arckon-installer</string>
  <key>CFBundleVersion</key>           <string>1</string>
  <key>CFBundleShortVersionString</key> <string>1.0</string>
  <key>CFBundlePackageType</key>       <string>APPL</string>
  <key>CFBundleExecutable</key>        <string>ArckonInstaller</string>
  <key>CFBundleInfoDictionaryVersion</key> <string>6.0</string>
  <key>LSMinimumSystemVersion</key>    <string>10.13</string>
  <key>NSHighResolutionCapable</key>   <true/>
</dict>
</plist>
"""


def _safe(value: str) -> str:
    """Escape characters that would break the NSIS script or shell script."""
    return value.replace('"', '').replace("'", "").replace("\\", "")


def generate_windows_installer(
    server_url: str,
    agent_token: str,
    customer_name: str,
    install_ps1_path: str,
    output_dir: str,
) -> str:
    """Compile a per-customer Windows .exe installer with NSIS.

    Returns the path to the generated ArckonAgentSetup.exe.
    Raises RuntimeError if makensis is not available.
    """
    if not shutil.which("makensis"):
        raise RuntimeError("makensis (NSIS) is not installed in the admin container")

    work = tempfile.mkdtemp(prefix="arckon-nsis-")
    try:
        nsi_path = os.path.join(work, "arckon-installer.nsi")
        exe_path = os.path.join(output_dir, f"ArckonAgentSetup-{INSTALLER_VERSION}.exe")

        nsi = _NSI_TEMPLATE
        nsi = nsi.replace("__SERVER__", _safe(server_url))
        nsi = nsi.replace("__TOKEN__", _safe(agent_token))
        nsi = nsi.replace("__CUSTOMER_NAME__", _safe(customer_name))
        nsi = nsi.replace("__INSTALLER_VERSION__", INSTALLER_VERSION)
        nsi = nsi.replace("__OUTPUT__", exe_path.replace("\\", "\\\\"))

        with open(nsi_path, "w", encoding="utf-8") as f:
            f.write(nsi)

        shutil.copy2(install_ps1_path, os.path.join(work, "install.ps1"))
        uninstall_ps1_path = os.path.join(os.path.dirname(install_ps1_path), "uninstall.ps1")
        if not os.path.isfile(uninstall_ps1_path):
            raise RuntimeError("uninstall.ps1 is missing from the installer directory")
        shutil.copy2(uninstall_ps1_path, os.path.join(work, "uninstall.ps1"))

        result = subprocess.run(
            ["makensis", nsi_path],
            capture_output=True, text=True, timeout=60, cwd=work,
        )
        if result.returncode != 0 or not os.path.isfile(exe_path):
            raise RuntimeError(f"NSIS compilation failed: {result.stderr or result.stdout}")

        return exe_path
    finally:
        shutil.rmtree(work, ignore_errors=True)


def generate_macos_installer(
    server_url: str,
    agent_token: str,
    customer_name: str,
    install_sh_path: str,
    output_dir: str,
) -> str:
    """Build a per-customer macOS .app bundle and zip it.

    Returns the path to the generated .zip file.
    """
    work = tempfile.mkdtemp(prefix="arckon-app-")
    try:
        app_dir = os.path.join(work, "Arckon Installer.app")
        contents = os.path.join(app_dir, "Contents")
        macos_dir = os.path.join(contents, "MacOS")
        resources_dir = os.path.join(contents, "Resources")
        os.makedirs(macos_dir)
        os.makedirs(resources_dir)

        with open(os.path.join(contents, "Info.plist"), "w", encoding="utf-8") as f:
            f.write(_INFO_PLIST)

        launcher_path = os.path.join(macos_dir, "ArckonInstaller")
        with open(launcher_path, "w", encoding="utf-8") as f:
            f.write(_APP_LAUNCHER)
        os.chmod(launcher_path, 0o755)

        shutil.copy2(install_sh_path, os.path.join(resources_dir, "install.sh"))
        os.chmod(os.path.join(resources_dir, "install.sh"), 0o755)

        with open(os.path.join(resources_dir, "server.txt"), "w", encoding="utf-8") as f:
            f.write(server_url + "\n")
        with open(os.path.join(resources_dir, "token.txt"), "w", encoding="utf-8") as f:
            f.write(agent_token + "\n")

        zip_path = os.path.join(output_dir, "ArckonInstaller-macOS.zip")
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for root, _dirs, files in os.walk(app_dir):
                for fname in files:
                    fpath = os.path.join(root, fname)
                    arcname = os.path.relpath(fpath, work)
                    zf.write(fpath, arcname)

        return zip_path
    finally:
        shutil.rmtree(work, ignore_errors=True)
